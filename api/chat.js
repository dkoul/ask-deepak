var DEFAULT_LIMITS = {
  ipPerMinute: 6,
  ipPerDay: 25,
  sessionPerHour: 12,
  globalDaily: 150,
  minIntervalSeconds: 2
};
var RateLimiter = class {
  constructor() {
    this.windows = /* @__PURE__ */ new Map();
    this.lastRequestByIp = /* @__PURE__ */ new Map();
  }
  checkWindow(key, limit, windowMs) {
    const now = Date.now();
    const entry = this.windows.get(key);
    if (!entry || now >= entry.resetAt) {
      this.windows.set(key, { count: 1, resetAt: now + windowMs });
      return { allowed: true };
    }
    if (entry.count >= limit) {
      return {
        allowed: false,
        retryAfterSeconds: Math.ceil((entry.resetAt - now) / 1e3),
        reason: "rate_limit"
      };
    }
    entry.count += 1;
    return { allowed: true };
  }
  check(ip, sessionId, config = DEFAULT_LIMITS) {
    const now = Date.now();
    const lastRequest = this.lastRequestByIp.get(ip);
    if (lastRequest && now - lastRequest < config.minIntervalSeconds * 1e3) {
      return {
        allowed: false,
        retryAfterSeconds: config.minIntervalSeconds,
        reason: "too_fast"
      };
    }
    const checks = [
      this.checkWindow(`ip:min:${ip}`, config.ipPerMinute, 60 * 1e3),
      this.checkWindow(`ip:day:${ip}`, config.ipPerDay, 24 * 60 * 60 * 1e3),
      this.checkWindow(`session:hour:${sessionId}`, config.sessionPerHour, 60 * 60 * 1e3),
      this.checkWindow("global:day", config.globalDaily, 24 * 60 * 60 * 1e3)
    ];
    const blocked = checks.find((c) => !c.allowed);
    if (blocked) {
      return blocked;
    }
    this.lastRequestByIp.set(ip, now);
    return { allowed: true };
  }
  /** Prune expired entries periodically to avoid memory growth */
  prune() {
    const now = Date.now();
    for (const [key, entry] of this.windows) {
      if (now >= entry.resetAt) {
        this.windows.delete(key);
      }
    }
  }
};

